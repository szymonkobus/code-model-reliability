"""Where each task comes from, and the attribution table built from it.

``attribution.jsonl`` has one row per member of the three sets: the set, the task id, whether it is kept and why
not, the family and kind (converted from a public dataset, a reworded copy of a wave 1 task, generated by seeded
template code, or model-generated and screened), the source set and row, the conversion or generation method, the
reference's origin, the generator and its settings, the licence the text travels under, the audit label, the status,
and the content hash. ``sources.json`` has one row per source set: what it is, the licence as recorded when the rows
were fetched, how its tasks are redistributed here, and which families of task ids it covers.

The attribution table of ``DATA-LICENSE.md`` and of the dataset's README is generated here from those two files.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from .content import SET_KEYS, SET_NAMES
from .records import iter_jsonl

REDISTRIBUTION = {
    "text": "full text, with attribution",
    "pointer": "identity, tests' hashes and a pointer to the source; the text rebuilds from the upstream",
    "ours": "full text, under this repository's data licence",
}
"""The three ways a source set's tasks ship, by the key ``redistribution`` of a source row."""


def load_attribution(tasks_dir: Path) -> list[dict]:
    return list(iter_jsonl(tasks_dir / "attribution.jsonl"))


def load_sources(tasks_dir: Path) -> list[dict]:
    return json.loads((tasks_dir / "sources.json").read_text(encoding="utf-8"))["sources"]


def source_of(row: dict, sources: list[dict]) -> dict | None:
    """The source row a task belongs to, by its family: a source lists the family prefixes it covers."""
    family = row.get("family", "")
    for src in sources:
        for prefix in src.get("families", []):
            if family == prefix or family.startswith(prefix + "/") or family.startswith(prefix + ":"):
                return src
    return None


def counts_by_source(rows: list[dict], sources: list[dict]) -> dict[str, Counter]:
    """Per source id, the number of tasks per set; ``None`` collects rows no source covers."""
    out: dict[str, Counter] = {src["id"]: Counter() for src in sources}
    out[None] = Counter()
    for row in rows:
        src = source_of(row, sources)
        out[src["id"] if src else None][row["set"]] += 1
    return out


def attribution_table(rows: list[dict], sources: list[dict]) -> str:
    """The attribution table as Markdown: one row per source set with its licence, how it ships and the counts."""
    counts = counts_by_source(rows, sources)
    head = ["source set", "what it is", "licence as recorded", "how its tasks ship here", *[SET_NAMES[k] for k in SET_KEYS]]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for src in sources:
        c = counts[src["id"]]
        cells = [
            src["name"],
            src.get("what_it_is", ""),
            src.get("licence_as_recorded", ""),
            REDISTRIBUTION.get(src.get("redistribution", ""), src.get("redistribution", "")),
            *[str(c.get(k, 0)) for k in SET_KEYS],
        ]
        lines.append("| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |")
    total = Counter()
    for c in counts.values():
        total.update(c)
    lines.append("| **all** | | | | " + " | ".join(f"**{total.get(k, 0)}**" for k in SET_KEYS) + " |")
    if counts[None]:
        lines.append("")
        lines.append(f"{sum(counts[None].values())} rows match no source set and are listed in the manifest.")
    return "\n".join(lines)


def check_attribution(rows: list[dict], sources: list[dict], members: dict[str, frozenset[str]]) -> list[str]:
    """One row per member of each set, no row outside the sets, every row covered by a source. Returns problems."""
    problems: list[str] = []
    seen: dict[str, set[str]] = {k: set() for k in SET_KEYS}
    for row in rows:
        key = row.get("set")
        if key not in seen:
            problems.append(f"attribution row {row.get('task_id')} names an unknown set {key!r}")
            continue
        if row["task_id"] in seen[key]:
            problems.append(f"attribution: {row['task_id']} appears twice in {key}")
        seen[key].add(row["task_id"])
        if source_of(row, sources) is None:
            problems.append(f"attribution: {row['task_id']} (family {row.get('family')!r}) matches no source set")
    for key, ids in members.items():
        missing = ids - seen.get(key, set())
        extra = seen.get(key, set()) - ids
        if missing:
            problems.append(f"attribution: {len(missing)} members of {key} have no row")
        if extra:
            problems.append(f"attribution: {len(extra)} rows of {key} are not members")
    return problems
